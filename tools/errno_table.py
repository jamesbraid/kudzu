#!/usr/bin/env python3
"""Error numbers that each 6.5.30 system call handler and syssgi selector returns directly.

Usage: tools/errno_table.py [--out evidence/inventory/errnos.tsv] [--binary 6.5.30/unix.IP35 ...]

Run it from the repository root with root/ populated, inside the toolchain container
(retools/tools/re-run python3 tools/errno_table.py). The handlers come from evidence/inventory/syscalls.tsv
(the `sysent` table) and the case code of each selector from evidence/inventory/selectors.tsv, both
generated by retools/tools/kudzu/os_tables.py, so run that first. A handler is read from its entry with the
symbolic engine in retools/tools/facts.py. A selector's case code is read from its own address to the end
of syssgi, so the common exit the cases branch to is part of the read.

One row per return path that leaves a value in v0, zero excluded (zero is success):

  value      the symbolic v0 on the path: a constant (0x16), a callee's return value (ret(lookupname)),
             a value the path merged from several constants (one row per constant, traced `merged`),
             or `?` when the engine did not resolve it
  errno      the constant in decimal; blank unless the value is a constant
  traced     `direct` for a constant the routine itself sets on that path, `merged` for one of a
             set of constants that reach the return together, `not traced` for a value passed through
             from a callee (the callee's own errno numbers are not read here), `unknown` otherwise
  from       the address of the instruction that leaves the path for the return block
  condition  the conditional branches on the way to that instruction, nearest first, each with its
             text and whether the path took it (`taken`) or fell through (`not taken`); the walk stops
             after three, and `...` marks a walk that had more
  grade      `established` when the value was read on the path in the binary, `inferred` for a merged
             value, `unknown` when the engine did not resolve the value

A routine whose name is ambiguous, or that is not in the image, gets one row with `grade` = `unknown`
and the reason in `condition`.
"""
import collections
import os
import re
import sys

os.environ['LC_ALL'] = os.environ['LANG'] = 'C'
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, 'retools', 'tools'))

import facts as F  # noqa: E402

RELEASE_BINARIES = ['6.5.30/unix.IP27', '6.5.30/unix.IP30', '6.5.30/unix.IP35']
CONST = re.compile(r'^-?0x[0-9a-f]+$')
CALLEE = re.compile(r'^ret\((.+)\)$')
ONE_OF = re.compile(r'^one of (.+)$')
DEPTH = 3
WALK_LIMIT = 200
JUMPS = {'j', 'jr', 'jr.hb', 'jal', 'jalr', 'jalr.hb', 'jalx'}


class EntryRoutine(F.Routine):
    """A routine read from an entry point inside it. The code before the entry is still read, so a case
    that branches back to the routine's common exit reaches that exit."""

    def __init__(self, img, name, start, size, section, entry):
        F.Routine.__init__(self, img, name, start, size, section, 'tools/errno_table.py', F.DEFAULT_ERRORS)
        self.entry = self.at[entry]
        self.case = entry

    def run(self):
        self.in_states = {self.entry: self.entry_state()}
        self.edges = {}
        work = [self.entry]
        visits = collections.Counter()
        while work:
            i = work.pop()
            visits[i] += 1
            if visits[i] > 400:
                continue
            st = self.in_states[i].copy()
            for j, out in self.successors(i, st):
                if j is None or j >= len(self.insns) or j < 0:
                    continue
                self.edges[(i, j)] = out
                old = self.in_states.get(j)
                new = out if old is None else F.meet_state(old, out)
                if old is None or new.key() != old.key():
                    self.in_states[j] = new
                    work.append(j)


def is_conditional(ins):
    return F.is_branch(ins['mn']) and ins['mn'] not in JUMPS and ins['mn'] not in F.CALLS


def conditions(r, rec, p, j):
    """Conditional branches on the way to the edge (p, j), nearest first: (texts, more)."""
    out = []
    more = False
    frontier = collections.deque([(p, j)])
    seen = set()
    steps = 0
    while frontier:
        a, b = frontier.popleft()
        if (a, b) in seen:
            continue
        seen.add((a, b))
        steps += 1
        if steps > WALK_LIMIT:
            more = True
            break
        ins = r.insns[a]
        if is_conditional(ins):
            st = r.in_states.get(a)
            never, always = r.static_cond(st, ins) if st is not None else (False, False)
            if not always and not never:
                t = F.branch_target(ins)
                taken = t is not None and r.at.get(t) == b
                text = '%s %s' % (rec.text(ins), 'taken' if taken else 'not taken')
                if text not in out:
                    out.append(text)
                if len(out) >= DEPTH:
                    more = True
                    break
        if a == 0:
            continue
        frontier.extend(sorted(k for k in r.edges if k[1] == a))
    return out, more


def block_start(r, i):
    j = i
    starts = r.branch_targets()
    while j > 0:
        prev = r.insns[j - 1]
        if j in starts or (j - 2 >= 0 and F.is_branch(r.insns[j - 2]['mn'])) or F.is_branch(prev['mn']):
            break
        j -= 1
    return j


def values(v0):
    """(value, errno, traced, grade) for each row a path's v0 gives."""
    if v0 is None or v0 == '?':
        return [(v0 or '?', '', 'unknown', 'unknown')]
    if CONST.match(v0):
        n = int(v0, 16)
        if n >= 1 << 63:
            n -= 1 << 64
        return [(v0, n, 'direct', 'established')]
    if CALLEE.match(v0):
        return [(v0, '', 'not traced', 'established')]
    m = ONE_OF.match(v0)
    if m:
        out = []
        for part in m.group(1).split(', '):
            if CONST.match(part):
                out.append((part, int(part, 16), 'merged', 'inferred'))
        if out:
            return out
    return [(v0, '', 'unknown', 'unknown')]


def rows_for(r):
    """Rows for one routine: (value, errno, traced, from, condition, grade) per path and value."""
    out = r.facts(False)
    rec = F.Recorder(r)
    rows = []
    for ex in out.get('exits', []):
        j = block_start(r, ex['index'])
        if not ex.get('paths'):
            # the return sits in the entry block, so no edge reaches it: its v0 is read at the return itself
            for v, n, traced, grade in values(ex.get('v0')):
                if traced in ('direct', 'merged') and n == 0:
                    continue
                rows.append((v, n, traced, ex['address'], '(none)', grade))
            continue
        for pth in ex['paths']:
            conds, more = conditions(r, rec, r.at.get(int(pth['from'], 16)), j)
            cond = '; '.join(conds) if conds else '(none)'
            if more:
                cond += '; ...'
            for v, n, traced, grade in values(pth.get('v0')):
                if traced in ('direct', 'merged') and n == 0:
                    continue
                rows.append((v, n, traced, pth['from'], cond, grade))
    return rows


def callees_of(rows):
    """First-level callees whose return value a handler's paths carry: names, or addresses for unnamed code."""
    out = collections.OrderedDict()
    for v, _n, traced, _frm, _cond, _grade in rows:
        m = CALLEE.match(v) if isinstance(v, str) else None
        if m and m.group(1) != '?':
            out.setdefault(m.group(1), None)
    return list(out)


def routine_rows(img, b, kind, ids, handler, r, out_rows):
    """Append the rows of a handler (level `handler`) and of its first-level callees (level `callee NAME`)."""
    rows = rows_for(r)
    for v, n, traced, frm, cond, grade in rows:
        out_rows.append((b, kind, ids, handler, 'handler', '0x%x' % getattr(r, 'case', r.addr), frm, v,
                         '' if n is None else n, traced, cond, grade))
    for name in callees_of(rows):
        try:
            if name.startswith('0x'):
                addr, size, sec = unnamed_routine(img, int(name, 16))
                label = 'sub_%s' % name[2:]
            else:
                _n, addr, size, sec, _src = img.find(name)
                label = name
        except SystemExit as e:
            out_rows.append((b, kind, ids, handler, 'callee %s' % name, name, '', '', '', 'unresolved',
                             str(e).splitlines()[0], 'unknown'))
            continue
        cr = F.Routine(img, label, addr, size, sec, 'tools/errno_table.py', F.DEFAULT_ERRORS)
        for v, n, traced, frm, cond, grade in rows_for(cr):
            out_rows.append((b, kind, ids, handler, 'callee %s' % label, '0x%x' % addr, frm, v,
                             '' if n is None else n, traced, cond, grade))


def unnamed_routine(img, addr):
    """Address, size and section of code with no symbol: up to the next function start in the section."""
    import bisect
    sec = img.section_of(addr)
    if not sec:
        raise SystemExit('facts: no section holds 0x%x' % addr)
    funcs = img.func_addrs
    i = bisect.bisect_right(funcs, addr)
    end = funcs[i] if i < len(funcs) else img.section_bounds(sec)[1]
    bounds = img.section_bounds(sec)
    end = min(end, bounds[1])
    if end <= addr:
        raise SystemExit('facts: no code size for 0x%x' % addr)
    return addr, end - addr, sec


def main():
    out_path = os.path.join(REPO, 'evidence', 'inventory', 'errnos.tsv')
    if '--out' in sys.argv:
        out_path = sys.argv[sys.argv.index('--out') + 1]
    binaries = list(RELEASE_BINARIES)
    if '--binary' in sys.argv:
        binaries = [sys.argv[k + 1] for k, a in enumerate(sys.argv) if a == '--binary']
    header = ['binary', 'kind', 'id', 'handler', 'level', 'routine', 'from', 'value', 'errno', 'traced',
              'condition', 'grade']
    rows = []
    syscalls = read_tsv(os.path.join(REPO, 'evidence', 'inventory', 'syscalls.tsv'))
    selectors = read_tsv(os.path.join(REPO, 'evidence', 'inventory', 'selectors.tsv'))
    for b in binaries:
        path = os.path.join(REPO, 'root', b)
        if not os.path.exists(path):
            print('missing %s' % b, file=sys.stderr)
            continue
        img = F.image(path)
        # system calls: one routine per handler name, with every native call number that points at it
        ids = collections.OrderedDict()
        for r_ in syscalls:
            if r_['binary'] == b and r_['table'] == 'sysent':
                ids.setdefault(r_['handler'], []).append(r_['number'])
        for name, numbers in ids.items():
            try:
                _n, addr, size, sec, _src = img.find(name)
            except SystemExit as e:
                rows.append((b, 'syscall', ','.join(numbers), name, 'handler', '', '', '', '', 'unresolved',
                             str(e).splitlines()[0], 'unknown'))
                continue
            r = F.Routine(img, name, addr, size, sec, 'tools/errno_table.py', F.DEFAULT_ERRORS)
            routine_rows(img, b, 'syscall', ','.join(numbers), name, r, rows)
        # syssgi selectors: from each case code to the end of syssgi
        try:
            _n, s_addr, s_size, sec, _src = img.find('syssgi')
        except SystemExit:
            continue
        targets = collections.OrderedDict()
        for r_ in selectors:
            if r_['binary'] == b:
                targets.setdefault(r_['target'], []).append(r_['selector'])
        for target, sels in targets.items():
            t = int(target, 16)
            if not s_addr <= t < s_addr + s_size:
                rows.append((b, 'syssgi', ','.join(sels), 'syssgi', 'handler', target, '', '', '', 'unresolved',
                             'case code outside syssgi', 'unknown'))
                continue
            r = EntryRoutine(img, 'syssgi', s_addr, s_size, sec, t)
            routine_rows(img, b, 'syssgi', ','.join(sels), 'syssgi', r, rows)
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('\t'.join(header) + '\n')
        for r_ in rows:
            f.write('\t'.join(str(x) for x in r_) + '\n')
    print('%s: %d rows' % (out_path, len(rows)))


def read_tsv(path):
    with open(path, encoding='utf-8') as f:
        head = f.readline().rstrip('\n').split('\t')
        return [dict(zip(head, ln.rstrip('\n').split('\t'))) for ln in f]


if __name__ == '__main__':
    main()
